# 世界观这一块不做任何"模板 / 非模板"的判断：玩家可能把模板删光，也可能把模板
# 改成自己的写法——界面里写什么就存什么，主程序就原样拼进 system。
# （曾经用"（玩家自填）"这类子串判断"没写"，结果保留标题就永远存不进去。）


def system_prompt(cfg):
    """按配置取出生效的系统提示词：玩家写的优先，留空用内置。"""
    txt = ((cfg or {}).get("system_prompt") or "").strip()
    return txt or DEFAULT_STYLE

